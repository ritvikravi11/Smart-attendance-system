"""
SQLAlchemy declarative base and shared mixins.

WHY THIS FILE EXISTS
--------------------
Every SQLAlchemy model must inherit from a common `Base` class. That base is
what SQLAlchemy uses to build its internal registry of tables -- it is how
Alembic later discovers your schema to generate migrations.

We also define mixins here. A mixin is a small class holding columns that many
tables share. Instead of copy-pasting `created_at` into fifteen models (and
inevitably getting one of them wrong), we define it once and inherit it.
This is the DRY principle applied to schema design.
"""

from datetime import datetime, timezone

from sqlalchemy import BigInteger, Boolean, DateTime, Integer, func, false as sa_false, true as sa_true
from sqlalchemy.orm import DeclarativeBase, Mapped, mapped_column

# SQLite only auto-increments columns defined as exactly "INTEGER PRIMARY KEY".
# BigInteger maps to BIGINT, which SQLite treats as a different type and does
# NOT auto-increment. This variant type emits BigInteger on PostgreSQL (where
# it is needed for 64-bit IDs) and plain Integer on SQLite (where INTEGER
# is required for ROWID auto-increment to work).
BigIntPK = BigInteger().with_variant(Integer, "sqlite")


class Base(DeclarativeBase):
    """
    The declarative base all models inherit from.

    SQLAlchemy 2.0 style: we subclass `DeclarativeBase` rather than calling
    the older `declarative_base()` factory function. The 2.0 style gives us
    real type annotations (`Mapped[int]`), which means your editor can
    autocomplete model attributes and mypy can type-check your queries.
    """

    # `type_annotation_map` lets us control how Python types map to SQL types.
    # Without this, SQLAlchemy would pick defaults that may not match what we
    # designed. Being explicit here means the generated DDL is predictable.
    pass


class TimestampMixin:
    """
    Adds created_at / updated_at to any model that inherits it.

    WHY TIMESTAMPTZ AND NOT TIMESTAMP
    ---------------------------------
    `TIMESTAMP` stores a wall-clock reading with no timezone attached -- "2026-08-06
    14:30" is ambiguous, because it does not say *where*. `TIMESTAMPTZ` stores an
    absolute moment in time, normalised to UTC internally.

    This matters concretely for attendance: a session that starts at 23:45 IST is
    18:15 UTC on the *same* day, but a naive TIMESTAMP column combined with a
    server in a different timezone will silently record it against the wrong date.
    That bug is miserable to diagnose weeks later.

    Rule for this project: store UTC everywhere, convert to IST only in the
    presentation layer.

    WHY server_default=func.now() AND NOT default=datetime.now
    ----------------------------------------------------------
    `server_default` puts the DEFAULT clause in the actual database schema, so
    the timestamp is generated by PostgreSQL. `default` would generate it in
    Python. The database version is correct because:
      1. It still works if a row is inserted by a script, a migration, or psql.
      2. All rows use one clock (the DB server's), not each app server's clock.
    """

    created_at: Mapped[datetime] = mapped_column(
        DateTime(timezone=True),
        nullable=False,
        server_default=func.now(),
        comment="Row creation time (UTC)",
    )

    updated_at: Mapped[datetime] = mapped_column(
        DateTime(timezone=True),
        nullable=False,
        server_default=func.now(),
        onupdate=func.now(),  # SQLAlchemy sets this on every UPDATE
        comment="Last modification time (UTC)",
    )


class SoftDeleteMixin:
    """
    Adds an `is_active` flag for soft deletion.

    WHY SOFT DELETE INSTEAD OF DELETE
    ---------------------------------
    Consider hard-deleting a student who has 200 attendance records. You have
    exactly three options, and two are unacceptable:

      1. CASCADE the delete -> destroys attendance history. The registrar
         cannot audit last semester. Unacceptable.
      2. RESTRICT the delete -> the DELETE fails with a foreign key error and
         the admin cannot remove the student at all. Frustrating and useless.
      3. Soft delete -> set is_active = FALSE. The student disappears from
         every list and dropdown, but history remains intact and referentially
         valid. Correct.

    Soft deletion is standard practice for any entity referenced by immutable
    historical records. The cost is that every query must filter on is_active,
    which is why the schema uses *partial indexes* (WHERE is_active = TRUE) --
    those indexes only cover live rows, so they stay small and fast even as
    deactivated rows accumulate.

    NOTE: `face_embeddings` is the deliberate exception. Biometric data must be
    genuinely erasable on request (right to erasure), so that table uses a real
    ON DELETE CASCADE. Privacy law overrides the convenience of soft deletion.
    """

    is_active: Mapped[bool] = mapped_column(
        Boolean,
        nullable=False,
        server_default=sa_true(),
        index=True,
        comment="Soft-delete flag; FALSE means deactivated, not removed",
    )


def utc_now() -> datetime:
    """
    Timezone-aware UTC timestamp for use in Python-side logic.

    Use this instead of `datetime.now()` or the deprecated `datetime.utcnow()`.
    `datetime.utcnow()` returns a *naive* datetime (no tzinfo), which compares
    incorrectly against timezone-aware values pulled from the database and is
    deprecated as of Python 3.12.
    """
    return datetime.now(timezone.utc)
