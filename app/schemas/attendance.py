"""
Pydantic schemas for the attendance engine.

Reminder of the split: models describe the DATABASE, schemas describe the API.
`AttendanceRecordResponse` deliberately omits nothing sensitive here, but the
principle still applies -- what leaves the server is an explicit decision.
"""

from datetime import date, datetime

from pydantic import BaseModel, ConfigDict, Field

from app.models.enums import AttendanceStatus, MarkingMethod, SessionStatus


# ---------------------------------------------------------------------------
# SESSIONS
# ---------------------------------------------------------------------------


class SessionCreate(BaseModel):
    offering_id: int = Field(..., description="Which offering this class belongs to")
    session_date: date | None = Field(
        None,
        description=(
            "Local calendar date of the class. Defaults to today in the "
            "institution's timezone. Sent explicitly so a 23:45 class is not "
            "filed under the wrong UTC day."
        ),
    )
    room: str | None = Field(None, max_length=30)
    late_threshold_minutes: int | None = Field(
        None,
        ge=1,
        le=120,
        description="Students recognised after this many minutes are marked LATE",
    )
    notes: str | None = Field(None, max_length=255)


class SessionResponse(BaseModel):
    model_config = ConfigDict(from_attributes=True)

    id: int
    offering_id: int
    session_date: date
    started_at: datetime
    ended_at: datetime | None
    status: str
    room: str | None
    late_threshold_minutes: int | None

    # Denormalised for display -- saves the frontend three extra requests
    subject_code: str | None = None
    subject_name: str | None = None
    section: str | None = None
    faculty_name: str | None = None

    # Live counts
    enrolled_count: int = 0
    present_count: int = 0
    absent_count: int = 0
    review_count: int = 0


class SessionCloseResponse(BaseModel):
    """Summary returned when a session is closed."""

    session_id: int
    status: str
    ended_at: datetime
    enrolled_count: int
    present_count: int
    late_count: int
    absent_count: int
    excused_count: int
    review_count: int
    auto_absent_created: int = Field(
        ..., description="Records generated by the set-difference at close"
    )


# ---------------------------------------------------------------------------
# RECORDS
# ---------------------------------------------------------------------------


class ManualMarkRequest(BaseModel):
    student_id: int
    status: AttendanceStatus = AttendanceStatus.PRESENT
    notes: str | None = Field(None, max_length=255)


class RecordUpdateRequest(BaseModel):
    """Correcting an existing record."""

    status: AttendanceStatus
    notes: str | None = Field(None, max_length=255)


class AttendanceRecordResponse(BaseModel):
    model_config = ConfigDict(from_attributes=True)

    id: int
    session_id: int
    student_id: int
    status: str
    method: str
    confidence: float | None
    needs_review: bool
    marked_at: datetime
    was_overridden: bool = False

    # Denormalised for tables
    student_name: str | None = None
    roll_number: str | None = None


class RosterEntry(BaseModel):
    """
    One row of the live session roster.

    Every enrolled student appears, marked or not -- which is what lets the
    faculty UI show "12 of 40 marked" without a second request.
    """

    student_id: int
    roll_number: str
    student_name: str
    face_enrolled: bool
    status: str | None = None      # None means not yet marked
    method: str | None = None
    confidence: float | None = None
    needs_review: bool = False
    marked_at: datetime | None = None


class SessionRosterResponse(BaseModel):
    session_id: int
    session_status: str
    enrolled_count: int
    marked_count: int
    entries: list[RosterEntry]


# ---------------------------------------------------------------------------
# RECOGNITION
# ---------------------------------------------------------------------------


class RecognisedFace(BaseModel):
    """One face from a submitted frame, with its outcome."""

    bbox: list[int] = Field(..., description="[x1, y1, x2, y2] in original frame coords")
    detection_score: float

    student_id: int | None = None
    student_name: str | None = None
    roll_number: str | None = None

    confidence: float = 0.0
    is_unknown: bool = False
    needs_review: bool = False

    quality_passed: bool = True
    quality_reason: str = "OK"

    marked: bool = Field(False, description="True if this produced a NEW record")
    already_marked: bool = Field(False, description="True if already present")
    rejected_reason: str | None = None


class RecognitionResponse(BaseModel):
    faces: list[RecognisedFace]
    processing_ms: int
    index_size: int


class MarkFaceResponse(BaseModel):
    faces: list[RecognisedFace]
    processing_ms: int
    newly_marked: int
    total_marked: int
    enrolled_count: int


class RecognitionHealthResponse(BaseModel):
    model_loaded: bool
    model_name: str
    model_version: str | None
    index_size: int
    index_memory_kb: float
    match_threshold: float
    review_threshold: float


# ---------------------------------------------------------------------------
# ANALYTICS
# ---------------------------------------------------------------------------


class SubjectAttendance(BaseModel):
    """
    Attendance for one student in one offering.

    `percentage` is None when no eligible sessions have occurred yet -- NOT
    zero. Returning 0% would flag every student as a defaulter on day one.
    """

    offering_id: int
    subject_code: str
    subject_name: str
    section: str
    faculty_name: str

    total_sessions: int = Field(..., description="Eligible closed sessions")
    present: int
    late: int
    absent: int
    excused: int

    attended: int = Field(..., description="present + late")
    denominator: int = Field(..., description="eligible - excused")
    percentage: float | None
    is_below_threshold: bool = False


class StudentAttendanceSummary(BaseModel):
    student_id: int
    roll_number: str
    student_name: str

    overall_percentage: float | None
    overall_attended: int
    overall_denominator: int
    is_defaulter: bool

    subjects: list[SubjectAttendance]


class FacultyOfferingSummary(BaseModel):
    """Aggregate view of one offering, for the faculty dashboard."""

    offering_id: int
    subject_code: str
    subject_name: str
    section: str
    academic_year: str

    enrolled_count: int
    total_sessions: int
    closed_sessions: int
    cancelled_sessions: int

    average_percentage: float | None
    defaulter_count: int


class FacultyAttendanceSummary(BaseModel):
    faculty_id: int
    faculty_name: str
    employee_code: str
    offerings: list[FacultyOfferingSummary]

    total_sessions_conducted: int
    total_students_taught: int


class DefaulterEntry(BaseModel):
    student_id: int
    roll_number: str
    student_name: str
    percentage: float
    attended: int
    denominator: int
    shortfall_sessions: int = Field(
        ..., description="Consecutive future sessions needed to reach the threshold"
    )


# ---------------------------------------------------------------------------
# CHART ANALYTICS
# ---------------------------------------------------------------------------


class DailyPoint(BaseModel):
    """One session's attendance. `rate` is null when no one was enrolled."""

    session_id: int
    date: str
    present: int
    late: int
    absent: int
    excused: int
    attended: int
    total: int
    rate: float | None


class MonthlyPoint(BaseModel):
    month: str
    label: str
    sessions: int
    present: int
    late: int
    absent: int
    attended: int
    total: int
    rate: float | None


class StudentPercentage(BaseModel):
    student_id: int
    roll_number: str
    student_name: str
    total_sessions: int
    present: int
    late: int
    absent: int
    excused: int
    attended: int
    denominator: int
    percentage: float | None
    is_below_threshold: bool


class SubjectPercentage(BaseModel):
    offering_id: int
    subject_code: str
    subject_name: str
    section: str
    enrolled_count: int
    attended: int
    denominator: int
    rate: float | None
    below_threshold_count: int


class AbsenteeEntry(BaseModel):
    student_id: int
    roll_number: str
    student_name: str
    absent: int
    attended: int
    total_sessions: int
    percentage: float | None
    is_below_threshold: bool


class DashboardSummary(BaseModel):
    enrolled: int
    class_average: float | None
    below_threshold: int
    threshold: float


class OfferingDashboard(BaseModel):
    """One consistent snapshot for all five charts."""

    offering_id: int
    daily: list[DailyPoint]
    monthly: list[MonthlyPoint]
    students: list[StudentPercentage]
    top_absentees: list[AbsenteeEntry]
    summary: DashboardSummary
